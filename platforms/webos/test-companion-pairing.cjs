const assert = require('node:assert/strict');
const {Pairing,token,code,hash}=require('./service/companion-pairing');
const config=require('../../companion/protocol/lan.json');
let saved=[], fail=false, writes=0;
const store={read:()=>saved,write(value){writes++; if(fail)throw Error('EACCES');saved=value;}};
const pairing=new Pairing(store,config), nonce=token(), now=1000;
let window=pairing.open(now);
assert.throws(()=>pairing.request(token(),'Phone',nonce,now));
for(const bad of ['', ' '.repeat(2), 'a'.repeat(65), 'invisible\u202e', 'control\u0001', 'tag\u{E0020}'])assert.throws(()=>pairing.request(window,bad,nonce,now));
const pending=pairing.request(window,'هاتف المنزل 📱',nonce,now);
assert.equal(pending.code,code(window,nonce));assert.match(pending.code,/^[0-9]{6}$/);
assert.deepEqual(pairing.request(window,pending.name,nonce,now),pending);
assert.throws(()=>pairing.request(window,'Other',token(),now));
assert.equal(pairing.poll(window,nonce,now),null);assert.equal(writes,0);
assert.throws(()=>pairing.approve(token(),now));
pairing.approve(nonce,now);const grant=pairing.poll(window,nonce,now);pairing.approve(nonce,now);
assert.deepEqual(pairing.poll(window,nonce,now),grant);assert.equal(writes,0,'approval does not persist an undelivered grant');
assert.equal(pairing.authenticate(grant.id,grant.secret),false);
assert.throws(()=>pairing.finish(grant.id,token(),now));
fail=true;assert.throws(()=>pairing.finish(grant.id,grant.secret,now),/EACCES/);
assert.equal(pairing.authenticate(grant.id,grant.secret),false);assert.deepEqual(pairing.poll(window,nonce,now),grant);
fail=false;pairing.finish(grant.id,grant.secret,now);
assert.equal(pairing.state(now).open,false);assert.equal(pairing.authenticate(grant.id,grant.secret),true);
assert.equal(JSON.stringify(saved).includes(grant.secret),false);assert.equal(saved[0].hash,hash(grant.secret));
assert.deepEqual(pairing.list(),[{id:grant.id,name:pending.name}]);
saved[0].name='external mutation';assert.equal(pairing.list()[0].name,pending.name,'store/caller cannot mutate authorization memory');
const restarted=new Pairing(store,config);assert.equal(restarted.authenticate(grant.id,grant.secret),true);
fail=true;assert.throws(()=>restarted.revoke(grant.id),/EACCES/);assert.equal(restarted.authenticate(grant.id,grant.secret),true);
fail=false;restarted.revoke(grant.id);assert.equal(restarted.authenticate(grant.id,grant.secret),false);
window=pairing.open(now);pairing.request(window,'Expired',nonce,now);pairing.approve(nonce,now);
const expires=pairing.poll(window,nonce,now);assert.throws(()=>pairing.finish(expires.id,expires.secret,now+config.pairWindowMillis));
assert.equal(pairing.authenticate(expires.id,expires.secret),false);
window=pairing.open(now);pairing.request(window,'Rejected',nonce,now);pairing.reject(nonce,now);assert.throws(()=>pairing.poll(window,nonce,now));
window=pairing.open(now);pairing.request(window,'Cancelled',nonce,now);pairing.approve(nonce,now);const cancelled=pairing.poll(window,nonce,now);pairing.close();
assert.throws(()=>pairing.finish(cancelled.id,cancelled.secret,now));
const otherTv=new Pairing({read:()=>[],write(){}},config);assert.equal(otherTv.authenticate(grant.id,grant.secret),false);
assert.throws(()=>new Pairing({read:()=>[{id:grant.id,name:'x',hash:hash(grant.secret)},{id:grant.id,name:'x',hash:hash(grant.secret)}]},config));
const limited=new Pairing({read:()=>[{id:grant.id,name:'x',hash:hash(grant.secret)}]}, {...config,maxPhones:1});assert.throws(()=>limited.open(now));
const names=new Pairing({read:()=>[],write(){}},config),nameWindow=names.open(now);
for(let point=0;point<=0x10ffff;point++){
  const text=String.fromCodePoint(point);
  if(/[\p{Cc}\p{Cf}]/u.test(text))assert.throws(()=>names.request(nameWindow,'phone'+text,nonce,now),'Reject Unicode control/format U+'+point.toString(16));
}
console.log('PASS: LG approval/completion, expiry, rejection/cancellation, credential isolation/restart/revocation, Unicode name controls and failed-store preservation.');
